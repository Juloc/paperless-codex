import { readFile, writeFile } from 'node:fs/promises';

const file = '/app/server.mjs';
let source = await readFile(file, 'utf8');

const insertMarker = '\n\nfunction metadataMergeSpec(kind) {';
const insertAt = source.indexOf(insertMarker);
if (insertAt < 0) throw new Error('Pipeline 15 patch failed: metadataMergeSpec marker not found');

const helpers = [
  "function unusedMetadataProtection(kind, item, taxonomy) {",
  "  if (kind === 'tag') {",
  "    if (item.is_inbox_tag) return 'Inbox-Tag';",
  "    const id = Number(item.id);",
  "    const hasChildren = taxonomy.tags.some(tag => Number(tag.parent ?? tag.tn_parent ?? 0) === id);",
  "    if (hasChildren) return 'Eltern-Tag mit Untertags';",
  "  }",
  "  if (String(item.match || '').trim()) return 'Explizite Matching-Regel';",
  "  return null;",
  "}",
  "",
  "function unusedMetadataEntry(kind, item, taxonomy) {",
  "  const rawCount = item.document_count ?? item.documentCount;",
  "  if (rawCount === undefined || rawCount === null || rawCount === '') return null;",
  "  const documentCount = Number(rawCount);",
  "  if (!Number.isFinite(documentCount) || documentCount !== 0) return null;",
  "  const protectedReason = unusedMetadataProtection(kind, item, taxonomy);",
  "  return {",
  "    id: Number(item.id),",
  "    name: String(item.name || ''),",
  "    documentCount: 0,",
  "    protected: Boolean(protectedReason),",
  "    protectedReason",
  "  };",
  "}",
  "",
  "async function unusedMetadataAudit() {",
  "  const taxonomy = await getTaxonomy();",
  "  const correspondents = taxonomy.correspondents.map(item => unusedMetadataEntry('correspondent', item, taxonomy)).filter(Boolean);",
  "  const documentTypes = taxonomy.documentTypes.map(item => unusedMetadataEntry('documentType', item, taxonomy)).filter(Boolean);",
  "  const tags = taxonomy.tags.map(item => unusedMetadataEntry('tag', item, taxonomy)).filter(Boolean);",
  "  const all = [...correspondents, ...documentTypes, ...tags];",
  "  return {",
  "    generatedAt: new Date().toISOString(),",
  "    counts: {",
  "      correspondents: correspondents.length,",
  "      documentTypes: documentTypes.length,",
  "      tags: tags.length,",
  "      safe: all.filter(item => !item.protected).length,",
  "      protected: all.filter(item => item.protected).length",
  "    },",
  "    correspondents,",
  "    documentTypes,",
  "    tags",
  "  };",
  "}",
  "",
  "function liveMetadataReferencePath(kind, id) {",
  "  if (kind === 'correspondent') return `/api/documents/?correspondent__id=${id}&page_size=1`;",
  "  if (kind === 'documentType') return `/api/documents/?document_type__id=${id}&page_size=1`;",
  "  if (kind === 'tag') return `/api/documents/?tags__id__all=${id}&page_size=1`;",
  "  return null;",
  "}",
  "",
  "function responseDocumentCount(body) {",
  "  if (Number.isFinite(Number(body?.count))) return Number(body.count);",
  "  if (Array.isArray(body?.results)) return body.results.length;",
  "  if (Array.isArray(body)) return body.length;",
  "  return 0;",
  "}",
  "",
  "async function pruneUnusedMetadata({ items, confirm }) {",
  "  if (confirm !== true) throw new Error('Prune requires confirm=true.');",
  "  const requested = (Array.isArray(items) ? items : []).slice(0, 500);",
  "  if (!requested.length) throw new Error('No metadata entries selected.');",
  "  const taxonomy = await getTaxonomy();",
  "  const specs = {",
  "    correspondent: { collection: 'correspondents', endpoint: '/api/correspondents/' },",
  "    documentType: { collection: 'documentTypes', endpoint: '/api/document_types/' },",
  "    tag: { collection: 'tags', endpoint: '/api/tags/' }",
  "  };",
  "  const results = [];",
  "",
  "  for (const requestedItem of requested) {",
  "    const kind = String(requestedItem?.kind || '');",
  "    const id = Number(requestedItem?.id);",
  "    const spec = specs[kind];",
  "    if (!spec || !Number.isInteger(id) || id <= 0) {",
  "      results.push({ kind, id, deleted: false, skipped: true, reason: 'Ungültiger Eintrag' });",
  "      continue;",
  "    }",
  "",
  "    const item = itemById(taxonomy[spec.collection] || [], id);",
  "    if (!item) {",
  "      results.push({ kind, id, deleted: false, skipped: true, reason: 'Bereits entfernt' });",
  "      continue;",
  "    }",
  "",
  "    const protectedReason = unusedMetadataProtection(kind, item, taxonomy);",
  "    if (protectedReason) {",
  "      results.push({ kind, id, name: item.name, deleted: false, skipped: true, reason: protectedReason });",
  "      continue;",
  "    }",
  "",
  "    const referencePath = liveMetadataReferencePath(kind, id);",
  "    const referenceBody = await paperlessJson(referencePath);",
  "    const liveCount = responseDocumentCount(referenceBody);",
  "    if (liveCount !== 0) {",
  "      results.push({ kind, id, name: item.name, deleted: false, skipped: true, reason: `Wird noch von ${liveCount} Dokument(en) verwendet`, liveCount });",
  "      continue;",
  "    }",
  "",
  "    try {",
  "      await paperlessFetch(`${spec.endpoint}${id}/`, { method: 'DELETE' });",
  "      results.push({ kind, id, name: item.name, deleted: true, skipped: false, liveCount: 0 });",
  "    } catch (error) {",
  "      results.push({ kind, id, name: item.name, deleted: false, skipped: false, reason: String(error?.message || error), liveCount: 0 });",
  "    }",
  "  }",
  "",
  "  return {",
  "    ok: results.every(item => item.deleted || item.skipped),",
  "    deleted: results.filter(item => item.deleted).length,",
  "    skipped: results.filter(item => item.skipped).length,",
  "    failed: results.filter(item => !item.deleted && !item.skipped).length,",
  "    results",
  "  };",
  "}"
].join('\n');

source = source.slice(0, insertAt) + '\n\n' + helpers + source.slice(insertAt);

const auditRoute = "    if (req.method === 'GET' && url.pathname === '/assistant/metadata/audit') return send(res, 200, await metadataAudit());";
if (!source.includes(auditRoute)) throw new Error('Pipeline 15 patch failed: audit route not found');
source = source.replace(auditRoute, [
  auditRoute,
  "    if (req.method === 'GET' && url.pathname === '/assistant/metadata/unused') return send(res, 200, await unusedMetadataAudit());",
  "    if (req.method === 'POST' && url.pathname === '/assistant/metadata/prune') return send(res, 200, await pruneUnusedMetadata(await readJson(req)));"
].join('\n'));

await writeFile(file, source);
